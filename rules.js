/** 지금 상태에서 켜지는 질문만 준다 */
export function asksFor(state) {
  const st = state || {};
  return ASK_BANK.filter((a) => {
    if (!a.when) return true;
    if (a.when.confirmed !== undefined && st.confirmed !== a.when.confirmed) return false;
    if (a.when.stage && !a.when.stage.includes(st.stage)) return false;
    return true;
  });
}

